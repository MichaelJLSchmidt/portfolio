// The last step of `npm run build` (after scripts/i18n-pages.mjs): what Netlify needs besides
// the static export in dist/, for SITE_ACCESS (src/hosting/config.ts; netlify.toml sets it per
// deploy context):
//
//   gated   (until launch, every context) the password gate: a Netlify Edge Function on every
//           path except the gate's own assets (.netlify/v1/edge-functions, Netlify's Frameworks
//           API), the gate page's fonts in dist/_gate/, and X-Robots-Tag: noindex everywhere
//   public  (production after launch) no gate, no edge function, indexable
//
// Both write dist/_redirects (domain aliases to PRIMARY_DOMAIN; gated: the gate's asset rewrite)
// and dist/_headers (long caching for hashed files): Netlify applies those per deploy.
import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { load, root } from '../load-ts.mjs'

const { PRIMARY_DOMAIN, REDIRECT_DOMAINS, gate, siteAccess } = await load('src/hosting/config.ts')

const dist = join(root, 'dist')
const edgeDir = join(root, '.netlify/v1/edge-functions')
const edgeEntry = join(edgeDir, 'site-gate.ts')
const access = siteAccess(process.env.SITE_ACCESS)
const generated = `# Generated by scripts/hosting/build.mjs (SITE_ACCESS=${access}).`
const lines = (...rows) => `${rows.flat().join('\n')}\n`
const write = (path, text) => {
  mkdirSync(dirname(join(dist, path)), { recursive: true })
  writeFileSync(join(dist, path), text)
}

// The gate exists only where this build creates it: a stale entry from an earlier local build must
// never reach another deploy.
rmSync(edgeEntry, { force: true })
rmSync(join(dist, gate.assetsDir), { recursive: true, force: true })

// REDIRECT_DOMAINS -> https://PRIMARY_DOMAIN, path kept. Forced, so they win over files. While gated,
// the edge function answers aliases first (it runs before these rules); these cover the paths it
// never sees.
const domainRedirects = REDIRECT_DOMAINS.flatMap((domain) =>
  ['http', 'https'].map((scheme) => `${scheme}://${domain}/*  https://${PRIMARY_DOMAIN}/:splat  301!`),
)
const immutable = '  Cache-Control: public, max-age=31536000, immutable'

if (access === 'public') {
  write('_redirects', lines(generated, domainRedirects))
  write('_headers', lines(generated, '/_next/static/*', immutable))
  console.log('Site access: public (no gate, indexable)')
} else {
  const { contentSecurityPolicy, copyAssets, pageModel } = await import('./gate-page.mjs')
  const assets = copyAssets(join(dist, gate.assetsDir), gate.assets)
  const page = pageModel(assets)
  write('_redirects', lines(generated, domainRedirects, `${gate.assets}*  ${gate.assetsDir}:splat  200`))
  write(
    '_headers',
    lines(
      generated,
      '/_next/static/*',
      immutable,
      `${gate.assets}*`,
      immutable,
      `${gate.assetsDir}*`,
      immutable,
      '/*',
      '  X-Robots-Tag: noindex, nofollow',
    ),
  )
  mkdirSync(edgeDir, { recursive: true })
  const handler = relative(edgeDir, join(root, 'src/hosting/gate-handler.ts')).replaceAll('\\', '/')
  writeFileSync(
    edgeEntry,
    [
      `// Generated by scripts/hosting/build.mjs (SITE_ACCESS=gated); not committed.`,
      `import { createGate } from '${handler}'`,
      ``,
      `export default createGate(${JSON.stringify({ page, csp: contentSecurityPolicy(page), immutable: ['/_next/static/'] })})`,
      ``,
      `export const config = {`,
      `  path: '/*',`,
      `  excludedPath: ['${gate.assets}*'],`,
      // An error in the gate stops the request: never fail open.
      `  onError: 'fail',`,
      `  name: 'Password gate',`,
      `  generator: 'scripts/hosting/build.mjs',`,
      `}`,
      ``,
    ].join('\n'),
  )
  console.log(`Site access: gated (password gate: ${relative(root, edgeEntry)}, ${gate.passwordEnv} at runtime)`)
}
