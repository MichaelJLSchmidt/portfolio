// Chapter numerals as SVG outlines (src/content/generated/numerals.ts), drawn by the `draw` reveal.
//
// Bricolage Grotesque, the site's display face, from its variable TTF (scripts/assets/, from the
// Google Fonts repository, OFL: scripts/assets/OFL-BricolageGrotesque.txt). The WOFF2 the site
// serves is not used: fontkit's getVariation is unreliable for WOFF / WOFF2 containers.
//
// The numeral style (src/styles/type.css .t-numeral): wght 300, opsz 96 (wdth at its default),
// lining tabular figures. Each digit 0–9 is that instance's glyph after the lnum / tnum
// substitutions, flipped to y-down on one shared baseline: the viewBox's top is the line box's top
// for line-height 0.8 (the half-leading model on the font's ascent and descent, as browsers lay
// out the text), so the SVG sits where the text numeral sat. Each glyph is split into its closed
// contours (one path each) for the drawing. Run before `next build` (npm run build does);
// the output is committed.
import { createRequire } from 'node:module'
import { execFileSync } from 'node:child_process'
import { existsSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const fontkit = require('fontkit')
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const FONT = join(root, 'scripts/assets/BricolageGrotesque[opsz,wdth,wght].ttf')
const OUT = join(root, 'src/content/generated/numerals.ts')
const AXES = { wght: 300, opsz: 96 }
const LEADING = 0.8 // --type-numeral-leading
const TRACKING = -0.04 // --type-numeral-tracking (em)

const base = fontkit.openSync(FONT)
const font = base.getVariation(AXES)
const upm = font.unitsPerEm
// Browsers use the OS/2 typo metrics when USE_TYPO_METRICS is set, else hhea.
const os2 = font['OS/2']
const useTypo = Boolean(os2?.fsSelection?.useTypoMetrics)
const ascent = useTypo ? os2.typoAscender : font.hhea.ascent
const descent = useTypo ? os2.typoDescender : font.hhea.descent // negative
const lineGap = 0 // line-height overrides the line gap
const content = ascent - descent + lineGap
const lineHeight = LEADING * upm
// Line box top in font units (y up): the content area centred in the line box.
const top = ascent + (lineHeight - content) / 2

const run = font.layout('0123456789', ['lnum', 'tnum'])
const r = (v) => Math.round(v * 10) / 10
const fmt = (v) => String(r(v)).replace(/^(-?)0\./, '$1.')

function contours(path) {
  const out = []
  let d = ''
  const pt = (x, y) => `${fmt(x)} ${fmt(top - y)}`
  for (const { command, args } of path.commands) {
    if (command === 'moveTo') {
      if (d) out.push(d)
      d = `M${pt(args[0], args[1])}`
    } else if (command === 'lineTo') d += `L${pt(args[0], args[1])}`
    else if (command === 'quadraticCurveTo') d += `Q${pt(args[0], args[1])} ${pt(args[2], args[3])}`
    else if (command === 'bezierCurveTo')
      d += `C${pt(args[0], args[1])} ${pt(args[2], args[3])} ${pt(args[4], args[5])}`
    else if (command === 'closePath') {
      d += 'Z'
      out.push(d)
      d = ''
    }
  }
  if (d) out.push(d)
  return out
}

const digits = {}
run.glyphs.forEach((glyph, i) => {
  digits[String(i)] = { advance: r(run.positions[i].xAdvance), name: glyph.name, contours: contours(glyph.path) }
})
const advances = new Set(Object.values(digits).map((d) => d.advance))
if (advances.size !== 1) throw new Error(`expected tabular figures, got advances ${[...advances]}`)

const data = {
  font: `Bricolage Grotesque, wght ${AXES.wght}, opsz ${AXES.opsz}, lnum + tnum`,
  unitsPerEm: upm,
  /** The line box (line-height 0.8): the viewBox height; y = 0 is its top. */
  lineHeight: r(lineHeight),
  /** Baseline, from the line box's top. */
  baseline: r(top),
  /** Letter spacing between digits (font units, the numeral's -0.04em). */
  tracking: r(TRACKING * upm),
  digits,
}
const body = JSON.stringify(data, null, 2).replace(/"([a-zA-Z]\w*)":/g, '$1:')
writeFileSync(
  OUT,
  `/*
 * Generated by scripts/build-numerals.mjs: do not edit. The chapter numerals' outlines (the
 * ChapterNumeral component, src/components/layout/numeral-breaker.tsx): Bricolage Grotesque at
 * wght ${AXES.wght} and opsz ${AXES.opsz}, lining tabular digits, in font units (y down, one baseline), each glyph split
 * into its closed contours. ${useTypo ? 'Typo' : 'hhea'} metrics: ascent ${ascent}, descent ${descent}.
 */
export type NumeralGlyph = { advance: number; name: string; contours: readonly string[] }

export const numerals = ${body} as const satisfies {
  font: string
  unitsPerEm: number
  lineHeight: number
  baseline: number
  tracking: number
  digits: Record<string, NumeralGlyph>
}
`,
)
// The repository's formatting (prettier), so a rebuild leaves the committed file unchanged.
const prettier = join(root, 'node_modules/prettier/bin/prettier.cjs')
if (existsSync(prettier)) execFileSync(process.execPath, [prettier, '--write', '--log-level', 'warn', OUT])
const sizes = Object.values(digits).map((d) => d.contours.length)
console.log(
  `numerals: ${OUT.replace(root + '/', '')} (contours per digit ${sizes.join(' ')}, advance ${[...advances][0]})`,
)
