// `npm run build`: builds the deploy for SITE_MODE (netlify.toml sets it per deploy context;
// modes are described in src/hosting/config.ts). Output goes to out/, Netlify's publish
// directory.
//
//   construction  the under-construction page only: no Next.js, no Three.js
//   basecamp      the full site, plus the password gate as a Netlify Edge Function
//                 (.netlify/v1/edge-functions, Netlify's Frameworks API)
//   live          the full site, no gate
//
// Without SITE_MODE it builds `live`. With NEXT_PUBLIC_PREVIEW=1 (local and CI previews)
// placeholders only warn. Each mode writes its own _redirects and _headers: Netlify applies those
// files per deploy, while netlify.toml headers would apply to every context alike.
import { spawnSync } from "node:child_process";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { BASECAMP_HOST, PRIMARY_DOMAIN, REDIRECT_DOMAINS, SITE_MODES, gate } from "../../src/hosting/config.ts";
import { renderPage, serialize } from "../../src/hosting/page.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const out = join(root, "out");
const edgeDir = join(root, ".netlify/v1/edge-functions");
const edgeEntry = join(edgeDir, "basecamp-gate.ts");

const mode = process.env.SITE_MODE || "live";
if (!SITE_MODES.includes(mode)) {
  console.error(`SITE_MODE "${mode}" is not one of ${SITE_MODES.join(", ")}.`);
  process.exit(1);
}
console.log(`Site mode: ${mode}`);

const run = (args, env = {}) => {
  const result = spawnSync(process.execPath, args, { cwd: root, stdio: "inherit", env: { ...process.env, ...env } });
  if (result.status !== 0) process.exit(result.status ?? 1);
};

// The gate exists only where this build creates it; a stale entry from an earlier local
// build must never reach another mode's deploy.
rmSync(edgeEntry, { force: true });
rmSync(out, { recursive: true, force: true });
run([join(root, "scripts/check-content.mjs"), "--build", `--mode=${mode}`]);

const lines = (...rows) => `${rows.flat().join("\n")}\n`;
const generated = `# Generated by scripts/site/build.mjs (SITE_MODE=${mode}).`;
const write = (path, text) => {
  mkdirSync(dirname(join(out, path)), { recursive: true });
  writeFileSync(join(out, path), text);
};

// REDIRECT_DOMAINS → https://PRIMARY_DOMAIN, path kept. Forced, so they win over files.
const domainRedirects = REDIRECT_DOMAINS.flatMap((domain) =>
  ["http", "https"].map((scheme) => `${scheme}://${domain}/*  https://${PRIMARY_DOMAIN}/:splat  301!`),
);
const immutable = "  Cache-Control: public, max-age=31536000, immutable";
const siteHeaders = [
  "/_next/static/*",
  immutable,
  // Terrain data changes only when the pipeline is re-run.
  "/terrain/*",
  "  Cache-Control: public, max-age=604800, stale-while-revalidate=86400",
];

if (mode === "construction") {
  const { contentSecurityPolicy, copyAssets, pageModel } = await import("./holding.mjs");
  const assets = copyAssets(join(out, "assets"), "/assets/");
  // A local preview build (NEXT_PUBLIC_PREVIEW=1, placeholders allowed) is noindex.
  const preview = process.env.NEXT_PUBLIC_PREVIEW === "1";
  const model = pageModel(assets, { canonical: preview ? null : `https://${PRIMARY_DOMAIN}/` });
  write("index.html", renderPage(model, { action: `https://${BASECAMP_HOST}${gate.unlock}`, next: "/", state: "idle" }));
  write("robots.txt", lines("User-agent: *", "Allow: /"));
  // Every other path goes back to the page. Not "/*": Netlify drops a splat rule that would also
  // match its own target "/". Not forced, so existing files are served as they are.
  write("_redirects", lines(generated, domainRedirects, "/:segment  /  302", "/:segment/*  /  302"));
  write(
    "_headers",
    lines(
      generated,
      "/*",
      `  Content-Security-Policy: ${contentSecurityPolicy(model, `https://${BASECAMP_HOST}`)}`,
      "  Referrer-Policy: strict-origin-when-cross-origin",
      "  X-Content-Type-Options: nosniff",
      "/assets/*",
      immutable,
    ),
  );
} else {
  const next = createRequire(import.meta.url).resolve("next/dist/bin/next");
  run([next, "build"]);
  if (mode === "live") {
    write("_redirects", lines(generated, domainRedirects));
    write("_headers", lines(generated, siteHeaders));
  } else {
    const { contentSecurityPolicy, copyAssets, pageModel } = await import("./holding.mjs");
    const assets = copyAssets(join(out, gate.assetsDir), gate.assets);
    const model = pageModel(assets, { canonical: null });
    write("_redirects", lines(generated, `${gate.assets}*  ${gate.assetsDir}:splat  200`));
    write(
      "_headers",
      lines(generated, siteHeaders, `${gate.assets}*`, immutable, `${gate.assetsDir}*`, immutable, "/*", "  X-Robots-Tag: noindex, nofollow"),
    );
    mkdirSync(edgeDir, { recursive: true });
    const handler = relative(edgeDir, join(root, "src/hosting/gate-handler.ts")).replaceAll("\\", "/");
    writeFileSync(
      edgeEntry,
      [
        `// Generated by scripts/site/build.mjs (SITE_MODE=basecamp); not committed.`,
        `import { createGate } from "${handler}";`,
        ``,
        `export default createGate(${JSON.stringify({ page: serialize(model), csp: contentSecurityPolicy(model, "'self'") })});`,
        ``,
        `export const config = {`,
        `  path: "/*",`,
        `  excludedPath: ["${gate.assets}*"],`,
        `  name: "Basecamp gate",`,
        `  generator: "scripts/site/build.mjs",`,
        `};`,
        ``,
      ].join("\n"),
    );
    console.log(`Basecamp gate: ${relative(root, edgeEntry)}`);
  }
}
console.log(`Built ${mode} into ${relative(root, out)}/`);
