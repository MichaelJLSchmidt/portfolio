"""
Logo lab: extract the M and F outlines of the site's display font.

Reads src/fonts/BricolageGrotesque-opsz-wght.latin.woff2 (variable: opsz 12-96,
wght 200-800) and writes src/lab/logo/glyphs.ts:
  - M and F as point contours at wght 800 / opsz 96 and wght 200 / opsz 96.
    Instances of a variable font share their point structure, so the two
    weights interpolate point for point (checked below).
  - The vertical stem width of H at the four axis corners and the cap height,
    so the lockup can pick the wordmark weight whose stem matches a mark's stroke.

Dev-only, not part of the site build. Requirements (Python 3.10+):
  python3 -m venv .venv && .venv/bin/pip install fonttools brotli
  .venv/bin/python -I src/lab/logo/tools/extract_glyphs.py
"""
import json
import pathlib
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import RecordingPen

ROOT = pathlib.Path(__file__).resolve().parents[4]
FONT = ROOT / "src/fonts/BricolageGrotesque-opsz-wght.latin.woff2"
OUT = ROOT / "src/lab/logo/glyphs.ts"

font = TTFont(FONT)
cmap = font.getBestCmap()
upm = font["head"].unitsPerEm


def contours(loc, ch):
    gs = font.getGlyphSet(location=loc)
    pen = RecordingPen()
    gs[cmap[ord(ch)]].draw(pen)
    out, cur = [], None
    for op, args in pen.value:
        if op == "moveTo":
            cur = [list(args[0])]
        elif op == "lineTo":
            cur.append(list(args[0]))
        elif op in ("closePath", "endPath"):
            out.append(cur)
            cur = None
        else:
            raise SystemExit(f"{ch} at {loc}: unexpected {op} (only straight outlines are supported)")
    return out, gs[cmap[ord(ch)]].width


def stem(loc):
    """Width of H's left stem: the first vertical edge pair of its outline."""
    cs, _ = contours(loc, "H")
    xs = sorted({round(p[0], 2) for p in cs[0]})
    return xs[1] - xs[0]


def cap(loc):
    cs, _ = contours(loc, "H")
    return max(p[1] for c in cs for p in c)


heavy = {"wght": 800, "opsz": 96}
light = {"wght": 200, "opsz": 96}
data = {}
for ch in "MF":
    h, hw = contours(heavy, ch)
    l, lw = contours(light, ch)
    if [len(c) for c in h] != [len(c) for c in l]:
        raise SystemExit(f"{ch}: point structure differs between weights")
    data[ch] = {"800": {"advance": hw, "contours": h}, "200": {"advance": lw, "contours": l}}

stems = {f"{o}-{w}": stem({"wght": w, "opsz": o}) for o in (12, 96) for w in (200, 800)}
caps = {o: cap({"wght": 800, "opsz": o}) for o in (12, 96)}
if len(set(caps.values())) != 1:
    raise SystemExit(f"cap height varies with opsz: {caps}")

header = """/*
 * Generated by src/lab/logo/tools/extract_glyphs.py from the site's display
 * font (Bricolage Grotesque, OFL). Do not edit by hand. Font units, y up,
 * baseline 0. Contours are point lists (the outlines are straight lines only);
 * the wght 200 and wght 800 instances share their point structure.
 */
"""
body = f"""export const fontUnits = {{ upm: {upm}, cap: {caps[96]} }} as const

/** H stem width (font units) at the axis corners, key `opsz-wght`. Bilinear in between. */
export const hStem = {json.dumps(stems)} as const

type Instance = {{ advance: number; contours: number[][][] }}

export const glyphs: Record<'M' | 'F', Record<'800' | '200', Instance>> = {json.dumps(data, separators=(',', ':'))}
"""
OUT.write_text(header + body)
print("wrote", OUT.relative_to(ROOT), "stems", stems, "cap", caps)
